#!/bin/zsh
# Lift FMOD's codec and DSP plugins as relocatable overlays.
#
#   tools/lift_fmod_plugins.sh
#
# spu_0002..spu_0019 in the EBOOT are FMOD Ex plugins (adpcm, mpeg, chorus,
# echo, reverb, lowpass...). The mixer (spu_0001) does not run them where they
# were linked: it DMAs each one's text straight out of the EBOOT into its own
# local store (e.g. spu_0019 text, EA 0x0089BA00, lands at LS 0x25910) and calls
# into it. lift_spu.sh lifts them at their link address, which never matches,
# so every plugin call fell to the SPU interpreter -- 84% of the mixer thread
# in a windowed session, too slow for its 5.3 ms blocks (slow, smeared in-game
# audio).
#
# The plugins are position independent (their text in local store is byte for
# byte the EBOOT's), so each is lifted once with spu_lifter.py --reloc at its
# link address and registered with spu_overlay_register_region_reloc: the GET
# that copies the text in makes the lift resident wherever it landed, and
# ctx->reloc_delta offsets the addresses it derives from its own pc.
#
# Output: port/spu/fmodplug_<image>/spu_recomp.{c,h} (never commit: derived from
# game code) and port/spu/fmodplug_register.c (EAs and sizes only).
# SPU_RELOC_OFF=1 at run time leaves the plugins to the interpreter again (A/B).
set -e
here=${0:A:h}; source "$here/env.sh"
"$PY" - "$AFRO_ANALYSIS/spu" "$AFRO_ROOT/port/spu" "$PS3RECOMP_DIR/tools" <<'PYEOF'
import glob, os, re, struct, subprocess, sys
imgdir, spudir, kit = sys.argv[1:4]
FIRST_IMAGE_ID = 40          # 1-20 EBOOT images, 21-22 jobs
EBOOT_TEXT_VA = 0x10000      # EBOOT file offset -> guest EA
plugs = []
for elf in sorted(glob.glob(f"{imgdir}/spu_*_at_*.elf")):
    m = re.match(r"spu_(\d{4})_at_([0-9A-F]{8})\.elf", os.path.basename(elf))
    idx, file_off = int(m.group(1)), int(m.group(2), 16)
    if not 2 <= idx <= 19:
        continue
    e = open(elf, "rb").read()
    phoff, = struct.unpack(">I", e[28:32]); phnum, = struct.unpack(">H", e[44:46])
    text = None
    for i in range(phnum):
        p_type, p_off, p_va, _, p_filesz, _, p_flags, _ = struct.unpack(">8I", e[phoff + 32 * i: phoff + 32 * i + 32])
        if p_type == 1 and p_flags & 1:
            text = (p_off, p_va, p_filesz)
            break
    if not text:
        continue
    stem = os.path.basename(elf)[:-4]
    prefix, out = f"fmodplug_{stem}_", f"{spudir}/fmodplug_{stem}"
    subprocess.check_call([sys.executable, f"{kit}/spu_lifter.py", elf, "--auto-functions", elf,
        "--symbol-prefix", prefix, "-o", out, "--reloc", "--merge-chunks",
        "--source-name", "spu_recomp.c", "--header-name", "spu_recomp.h"],
        stdout=subprocess.DEVNULL)
    ea = EBOOT_TEXT_VA + file_off + text[0]
    plugs.append((stem, prefix, ea, text[2], text[1]))
    print(f"[lift_fmod_plugins] {stem}: text EA 0x{ea:08X} +0x{text[2]:X}, canon 0x{text[1]:X}")

with open(f"{spudir}/fmodplug_register.c", "w") as f:
    f.write("/* GENERATED by tools/lift_fmod_plugins.sh: FMOD plugins as relocatable overlays. */\n")
    f.write("#include <stdint.h>\n")
    f.write("extern void spu_begin_image(int image_id);\n")
    f.write("extern void spu_overlay_register_region_reloc(uint32_t content_ea, uint32_t span,"
            " uint32_t canon, int image_id);\n")
    for stem, prefix, *_ in plugs:
        f.write(f"extern void {prefix}spu_recomp_register(void);\n")
    f.write("__attribute__((constructor)) static void fmodplug_register(void)\n{\n")
    for i, (stem, prefix, ea, size, canon) in enumerate(plugs):
        img = FIRST_IMAGE_ID + i
        f.write(f"    spu_begin_image({img}); {prefix}spu_recomp_register();\n")
        f.write(f"    spu_overlay_register_region_reloc(0x{ea:08X}u, 0x{size:X}u, 0x{canon:X}u, {img});\n")
    f.write("    spu_begin_image(0);\n}\n")
print(f"{len(plugs)} plugin(s) lifted")
PYEOF
